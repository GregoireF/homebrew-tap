require "json"

module Tap
  module Targets
    # aqua/registry.yaml: an aqua (https://aquaproj.github.io) registry with a
    # github_release package per tool: archive per platform, binaries, and the
    # release's checksums file, which aqua verifies on download. Templated on
    # the version, so it does not change with every release; it changes when
    # tools.yml does.
    module Aqua
      GLOBS = %w[aqua/registry.yaml].freeze
      PATH = "aqua/registry.yaml"
      SCHEMA = "https://raw.githubusercontent.com/aquaproj/aqua/main/json-schema/registry.json"
      FORMATS = { ".tar.gz" => "tar.gz", ".tgz" => "tgz", ".tar.xz" => "tar.xz", ".zip" => "zip" }.freeze
      DEFAULT = "linux_amd64"

      module_function

      def files(catalog)
        tools = catalog.tools
        return {} if tools.empty?

        { PATH => "# Generated by bin/tap from tools.yml. Do not edit.\n" \
                  "# yaml-language-server: $schema=#{SCHEMA}\npackages:\n#{tools.map { |t| package(t) }.join}" }
      end

      def package(tool)
        owner, name = tool.repo.split("/", 2)
        lines = [
          "  - type: github_release",
          "    repo_owner: #{q owner}",
          "    repo_name: #{q name}",
          "    description: #{q tool.desc}",
          "    asset: #{q asset(tool, DEFAULT)}",
          "    format: #{format(tool, DEFAULT)}",
          "    files:",
          *files_for(tool, DEFAULT, "    "),
          "    checksum:",
          "      type: github_release",
          "      asset: #{q tool.checksums}",
          "      algorithm: sha256",
          "    supported_envs: [darwin, linux, windows]",
          "    overrides:",
        ]
        (PLATFORMS - [DEFAULT]).each do |platform|
          goos, goarch = platform.split("_")
          lines << "      - goos: #{goos}"
          lines << "        goarch: #{goarch}"
          lines << "        asset: #{q asset(tool, platform)}"
          lines << "        format: #{format(tool, platform)}"
          lines << "        files:"
          lines.concat(files_for(tool, platform, "        "))
        end
        "#{lines.join("\n")}\n"
      end

      # The binaries and where they sit in that platform's archive.
      def files_for(tool, platform, indent)
        windows = platform.start_with?("windows")
        tool.binaries.flat_map do |binary|
          src = windows ? "#{binary}.exe" : binary
          src = "{{.AssetWithoutExt}}/#{src}" if tool.nested && !windows
          ["#{indent}  - name: #{q binary}", "#{indent}    src: #{q src}"]
        end
      end

      def asset(tool, platform) = tool.assets.fetch(platform).gsub("{version}", "{{trimV .Version}}")

      def format(tool, platform)
        name = tool.assets.fetch(platform)
        found = FORMATS.find { |ext, _| name.end_with?(ext) }
        found&.last || raise(Error, "#{tool.name}: unknown archive format #{name}")
      end

      def q(text) = JSON.generate(text.to_s)
    end
  end
end
