require "json"

module Tap
  module Targets
    # The reference pages of docs/, written from what they describe so they
    # cannot drift: tools.yml's keys from schema/tools.schema.json, the API
    # from schema/api.schema.json, the commands from bin/tap's usage.
    module Docs
      GLOBS = %w[docs/reference/*.md].freeze
      HEADER = "<!-- Generated by bin/tap render. Do not edit: change the source it names. -->\n\n"

      module_function

      def files(_catalog)
        {
          "docs/reference/tools-yml.md" => tools_yml,
          "docs/reference/api.md"       => api,
          "docs/reference/cli.md"       => cli,
        }
      end

      def schema(name) = JSON.parse(File.binread(File.join(Targets::ROOT, "schema", name)))

      def tools_yml
        tool = schema("tools.schema.json").dig("$defs", "tool")
        required = tool.fetch("required")
        rows = tool.fetch("properties").map { |key, spec| row(key, required, spec) }
        platforms = PLATFORMS.map { |p| "`#{p}`" }.join(", ")
        <<~MD
          #{HEADER.chomp}
          # `tools.yml` keys

          Source: [`schema/tools.schema.json`](../../schema/tools.schema.json), which
          editors with the YAML language server use for completion; `lib/tap/config.rb`
          enforces the same rules.

          Top level: `publisher` (the WinGet publisher name) and `tools`, a mapping
          from each tool's name (`[a-z0-9-]+`) to the keys below.

          | Key | Required | Type | Meaning |
          | --- | --- | --- | --- |
          #{rows.join("\n")}

          Platforms of `assets`: #{platforms}.
        MD
      end

      def api
        defs = schema("api.schema.json").fetch("$defs")
        sections = %w[index summary tool archive].map do |name|
          spec = defs.fetch(name)
          rows = spec.fetch("properties").map { |key, prop| row(key, spec.fetch("required"), prop) }
          "## `#{name}`\n\n| Field | Required | Type | Meaning |\n| --- | --- | --- | --- |\n#{rows.join("\n")}\n"
        end
        <<~MD
          #{HEADER.chomp}
          # API v1

          Source: [`schema/api.schema.json`](../../schema/api.schema.json), served as
          <#{Pages::URL}/api/v1/schema.json>.

          | URL | Object |
          | --- | --- |
          | `#{Pages::URL}/api/v1/tools.json` | `index` |
          | `#{Pages::URL}/api/v1/tools/<name>.json` | `tool` |

          ```sh
          curl -fsSL #{Pages::URL}/api/v1/tools/kiwa.json | jq -r '.archives.linux_amd64.url'
          ```

          #{sections.join("\n")}
        MD
      end

      def cli
        <<~MD
          #{HEADER.chomp}
          # `bin/tap`

          Source: `Tap::CLI::USAGE` in [`lib/tap/cli.rb`](../../lib/tap/cli.rb).

          ```text
          #{CLI::USAGE.chomp}
          ```
        MD
      end

      def row(key, required, spec)
        needed = required.include?(key) ? "yes" : "no"
        "| `#{key}` | #{needed} | #{type(spec)} | #{cell(spec["description"])} |"
      end

      def type(spec)
        ref = spec["$ref"]&.split("/")&.last
        return "list of strings" if ref == "strings"
        return "`#{ref}`" if ref
        return spec["enum"].map { |v| "`#{v}`" }.join(" or ") if spec["enum"]

        Array(spec["type"]).join(" or ")
      end

      def cell(text) = text.to_s.gsub("|", "\\|").gsub("<", "&lt;").gsub(">", "&gt;").tr("\n", " ")
    end
  end
end
