require "json"

module Tap
  # WinGet manifests (schema 1.10.0, multi-file: version, installer,
  # defaultLocale) for a tool with a `winget` identifier. They sit in
  # winget/manifests/ with winget-pkgs' layout, so `komac submit` can send
  # them to microsoft/winget-pkgs as they are. The zip archives are installed
  # as portable packages: no admin rights, one command alias per binary.
  module Winget
    MANIFEST_VERSION = "1.10.0"
    SCHEMA = "https://aka.ms/winget-manifest.%<type>s.#{MANIFEST_VERSION}.schema.json".freeze
    ARCHITECTURES = { "x64" => "windows_amd64", "arm64" => "windows_arm64" }.freeze

    module_function

    # winget/manifests/<letter>/<Publisher>/<Name>/<version>/
    def directory(tool, release)
      publisher, name = tool.winget.split(".", 2)
      "winget/manifests/#{publisher[0].downcase}/#{publisher}/#{name}/#{release.version}"
    end

    # { relative path => content } for the three manifests of the release.
    def files(tool, release)
      dir = directory(tool, release)
      {
        "#{dir}/#{tool.winget}.yaml"              => version_manifest(tool, release),
        "#{dir}/#{tool.winget}.installer.yaml"    => installer_manifest(tool, release),
        "#{dir}/#{tool.winget}.locale.en-US.yaml" => locale_manifest(tool, release),
      }
    end

    def version_manifest(tool, release)
      document("version", [
        ["PackageIdentifier", tool.winget],
        ["PackageVersion", release.version],
        ["DefaultLocale", "en-US"],
      ])
    end

    def installer_manifest(tool, release)
      lines = [
        ["PackageIdentifier", tool.winget],
        ["PackageVersion", release.version],
        ["InstallerType", "zip"],
        ["NestedInstallerType", "portable"],
      ]
      body = +"NestedInstallerFiles:\n"
      tool.binaries.each do |binary|
        body << "- RelativeFilePath: #{scalar("#{binary}.exe")}\n"
        body << "  PortableCommandAlias: #{scalar(binary)}\n"
      end
      body << "ReleaseDate: #{release.published[0, 10]}\n" if release.published
      body << "Installers:\n"
      ARCHITECTURES.each do |arch, platform|
        body << "- Architecture: #{arch}\n"
        body << "  InstallerUrl: #{scalar(release.url(tool, platform))}\n"
        body << "  InstallerSha256: #{release.sha256(platform).upcase}\n"
      end
      document("installer", lines, body)
    end

    def locale_manifest(tool, release)
      owner = tool.repo.split("/").first
      lines = [
        ["PackageIdentifier", tool.winget],
        ["PackageVersion", release.version],
        ["PackageLocale", "en-US"],
        ["Publisher", tool.publisher],
        ["PublisherUrl", "https://github.com/#{owner}"],
        ["PublisherSupportUrl", "#{tool.homepage}/issues"],
        ["PackageName", tool.name],
        ["PackageUrl", tool.homepage],
        ["License", tool.license],
        ["ShortDescription", tool.desc],
        ["ReleaseNotesUrl", "#{tool.homepage}/releases/tag/#{release.tag}"],
      ]
      document("defaultLocale", lines)
    end

    def document(type, lines, extra = "")
      head = "# Generated by bin/tap from tools.yml. Do not edit: the next sync rewrites it.\n" \
             "# yaml-language-server: $schema=#{format(SCHEMA, type:)}\n"
      pairs = lines.map { |key, value| "#{key}: #{scalar(value)}\n" }.join
      "#{head}#{pairs}#{extra}ManifestType: #{type}\nManifestVersion: #{MANIFEST_VERSION}\n"
    end

    # A YAML scalar: bare when unambiguous, otherwise a JSON string (valid YAML).
    def scalar(value)
      text = value.to_s
      return text if text.match?(%r{\A[A-Za-z0-9][\w.+/-]*\z}) && !text.match?(/\A[\d.]+\z/)

      JSON.generate(text)
    end
  end
end
